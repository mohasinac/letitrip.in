#!/usr/bin/env node
/*
 * WHY: /tools/authenticity has to answer "does this NAME match this CODE" with
 *      zero Firestore reads (Rule #6). That needs a bundled name->code index,
 *      and hand-typing 220 names plus their codes out of a 390 KB corpus is how
 *      a wrong code gets asserted at a buyer who is about to spend money.
 *
 * WHAT: Emits src/features/authenticity/data/canonical-index.generated.ts from
 *       `buildCanonicalIndex()`. The PARSE lives in scripts/lib/authenticity-sources.mjs
 *       and is shared with the Firestore seed emitter, so the two deliveries of
 *       this data cannot drift (Root Cause #75).
 *
 * 🛑 FACTS ONLY. Names, product codes and eras are taken from the corpus as
 *    facts (it derives from Fandom, CC-BY-SA). No corpus prose is copied — this
 *    emits no sentences at all. See docs/research/bey-corpus-2026-10/README.md.
 *
 * Run: node scripts/gen-authenticity-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { buildCanonicalIndex } from "./lib/authenticity-sources.mjs";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "src/features/authenticity/data/canonical-index.generated.ts");

const entries = buildCanonicalIndex();

const byGeneration = entries.reduce((acc, e) => {
  acc[e.generation] = (acc[e.generation] ?? 0) + 1;
  return acc;
}, {});
const withCode = entries.filter((e) => e.code).length;

const body = entries
  .map(
    (e) =>
      `  { slug: ${JSON.stringify(e.slug)}, name: ${JSON.stringify(e.name)}, ` +
      `code: ${e.code === null ? "null" : JSON.stringify(e.code)}, ` +
      `generation: ${JSON.stringify(e.generation)}, ` +
      `categoryId: ${JSON.stringify(e.categoryId)}, ` +
      `aliases: ${JSON.stringify(e.aliases)} },`,
  )
  .join("\n");

const out = `/**
 * GENERATED by scripts/gen-authenticity-index.mjs — do not edit by hand.
 *
 * Source: docs/research/bey-corpus-2026-10/canonical-beys.json (\`canonical\`
 * only; \`review\` and \`excluded\` are deliberately omitted as unsettled).
 *
 * ${entries.length} beys · ${withCode} carry a retail product code
 * ${Object.entries(byGeneration)
   .sort()
   .map(([g, n]) => `\n * ${g}: ${n}`)
   .join("")}
 *
 * Re-run after any corpus change: node scripts/gen-authenticity-index.mjs
 */
import type { GenerationId } from "../types";

export interface CanonicalBey {
  readonly slug: string;
  readonly name: string;
  /** Retail product code (\`BB-105\`, \`B-174\`, \`MA-09\`), or null where the release has none. */
  readonly code: string | null;
  readonly generation: GenerationId;
  /** The real category leaf id, so a match can link at its own page. */
  readonly categoryId: string;
  /** Japanese, romanised and Hasbro-retail spellings. Lookup only, never displayed. */
  readonly aliases: readonly string[];
}

export const CANONICAL_BEYS: readonly CanonicalBey[] = [
${body}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
console.log(
  `gen-authenticity-index: wrote ${entries.length} beys (${withCode} with codes) -> ${path.relative(ROOT, OUT)}`,
);
console.log(`  by generation: ${JSON.stringify(byGeneration)}`);
