#!/usr/bin/env node
/*
 * WHY: /tools/authenticity has to answer "does this NAME match this CODE" with
 *      zero Firestore reads (Rule #6). That needs a bundled name->code index,
 *      and hand-typing 220 names plus their codes out of a 390 KB corpus is how
 *      a wrong code gets asserted at a buyer who is about to spend money.
 *
 * WHAT: Emits src/features/authenticity/data/canonical-index.generated.ts from
 *       `buildCanonicalIndex()`. The PARSE lives in scripts/lib/authenticity-sources.mjs
 *       and is shared with the Firestore seed emitter, so the two deliveries of
 *       this data cannot drift (Root Cause #75).
 *
 * 🛑 FACTS ONLY. Names, product codes and eras are taken from the corpus as
 *    facts (it derives from Fandom, CC-BY-SA). No corpus prose is copied — this
 *    emits no sentences at all. See docs/research/bey-corpus-2026-10/README.md.
 *
 * Run: node scripts/gen-authenticity-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import {
  buildCanonicalIndex,
  buildDateCodeTables,
  buildModelCodeIndex,
} from "./lib/authenticity-sources.mjs";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "src/features/authenticity/data/canonical-index.generated.ts");
const OUT_MODEL_CODES = path.join(ROOT, "src/features/authenticity/data/model-codes.generated.ts");
const OUT_MODEL_OPTIONS = path.join(ROOT, "src/features/authenticity/data/model-options.generated.ts");

const entries = buildCanonicalIndex();
const { models: modelCodes } = buildModelCodeIndex(buildDateCodeTables(), entries);
const codeCountBySlug = new Map(
  modelCodes.map((m) => [
    m.slug,
    m.originalCodes.length + m.midfakeCodes.length + m.contestedCodes.length + m.unclearCodes.length,
  ]),
);

const byGeneration = entries.reduce((acc, e) => {
  acc[e.generation] = (acc[e.generation] ?? 0) + 1;
  return acc;
}, {});
const withCode = entries.filter((e) => e.code).length;

const body = entries
  .map(
    (e) =>
      `  { slug: ${JSON.stringify(e.slug)}, name: ${JSON.stringify(e.name)}, ` +
      `code: ${e.code === null ? "null" : JSON.stringify(e.code)}, ` +
      `generation: ${JSON.stringify(e.generation)}, ` +
      `categoryId: ${JSON.stringify(e.categoryId)}, ` +
      `aliases: ${JSON.stringify(e.aliases)} },`,
  )
  .join("\n");

const out = `/**
 * GENERATED by scripts/gen-authenticity-index.mjs — do not edit by hand.
 *
 * Source: docs/research/bey-corpus-2026-10/canonical-beys.json (\`canonical\`
 * only; \`review\` and \`excluded\` are deliberately omitted as unsettled).
 *
 * ${entries.length} beys · ${withCode} carry a retail product code
 * ${Object.entries(byGeneration)
   .sort()
   .map(([g, n]) => `\n * ${g}: ${n}`)
   .join("")}
 *
 * Re-run after any corpus change: node scripts/gen-authenticity-index.mjs
 */
import type { GenerationId } from "../types";

export interface CanonicalBey {
  readonly slug: string;
  readonly name: string;
  /** Retail product code (\`BB-105\`, \`B-174\`, \`MA-09\`), or null where the release has none. */
  readonly code: string | null;
  readonly generation: GenerationId;
  /** The real category leaf id, so a match can link at its own page. */
  readonly categoryId: string;
  /** Japanese, romanised and Hasbro-retail spellings. Lookup only, never displayed. */
  readonly aliases: readonly string[];
}

export const CANONICAL_BEYS: readonly CanonicalBey[] = [
${body}
];
`;

/* ----------------------------------------------------------- model codes -- */

/**
 * The reverse index — "what box codes are recorded for THIS bey".
 *
 * Emitted separately from `CANONICAL_BEYS` rather than folded into it because
 * the two have different readers and very different weights: every bey needs a
 * name and a retail code, only 38 have recorded box codes, and those 38 carry
 * ~700 code strings between them. A tool page that only needs the names must
 * not pull the codes in with them.
 */
const modelCodesBody = modelCodes
  .map(
    (m) =>
      `  {\n` +
      `    slug: ${JSON.stringify(m.slug)},\n` +
      `    name: ${JSON.stringify(m.name)},\n` +
      `    categoryId: ${JSON.stringify(m.categoryId)},\n` +
      `    generation: ${JSON.stringify(m.generation)},\n` +
      `    retailCode: ${m.code === null ? "null" : JSON.stringify(m.code)},\n` +
      `    originalCodes: ${JSON.stringify(m.originalCodes)},\n` +
      `    midfakeCodes: ${JSON.stringify(m.midfakeCodes)},\n` +
      `    contestedCodes: ${JSON.stringify(m.contestedCodes)},\n` +
      `    unclearCodes: ${JSON.stringify(m.unclearCodes)},\n` +
      `  },`,
  )
  .join("\n");

const modelCodesOut = `/**
 * GENERATED by scripts/gen-authenticity-index.mjs — do not edit by hand.
 *
 * What box codes are recorded against each bey — the REVERSE of the code
 * tables, which are keyed by code.
 *
 * 🛑 This answers a question the tool could not previously answer AT ALL. Every
 * table was keyed by code, so a user who named a model and had no code in front
 * of them got "inconclusive" and a physical checklist, when the honest answer
 * was "here are the ${modelCodes.reduce((n, m) => n + m.originalCodes.length, 0)} codes recorded on genuine boxes of these beys — check
 * yours against them".
 *
 * 🛑 ABSENCE IS NOT EVIDENCE, in either direction. ${modelCodes.length} of ${entries.length} canonical beys
 * have any recorded code at all, because the community tables cover what
 * collectors photographed, not what was manufactured. A model with no row here
 * is unrecorded, never suspect; a code not in a model's list is unrecorded, never
 * fake. The engine's copy says so in the same words.
 *
 * Re-run after any corpus or source change: node scripts/gen-authenticity-index.mjs
 */
import type { GenerationId } from "../types";

export interface ModelCodeRecord {
  readonly slug: string;
  readonly name: string;
  /** The real category leaf id — the join key every other surface uses. */
  readonly categoryId: string;
  readonly generation: GenerationId;
  /** The RETAIL product code (\`BB-43\`), not a box date code. */
  readonly retailCode: string | null;
  /** Box date codes recorded on genuine boxes of this bey. */
  readonly originalCodes: readonly string[];
  /** Box date codes recorded on a midfake batch of this bey. */
  readonly midfakeCodes: readonly string[];
  /** Codes the sources flatly disagree about. Never quoted one-sided. */
  readonly contestedCodes: readonly string[];
  /** Recorded but unresolved. */
  readonly unclearCodes: readonly string[];
}

export const MODEL_CODES: readonly ModelCodeRecord[] = [
${modelCodesBody}
];

const BY_SLUG = new Map(MODEL_CODES.map((m) => [m.slug, m]));
const BY_CATEGORY = new Map(MODEL_CODES.map((m) => [m.categoryId, m]));

/** Null when nothing is recorded for that bey — which is the common case. */
export function modelCodesFor(slugOrCategoryId: string): ModelCodeRecord | null {
  return BY_SLUG.get(slugOrCategoryId) ?? BY_CATEGORY.get(slugOrCategoryId) ?? null;
}
`;

/* --------------------------------------------------------- model options -- */

/**
 * The picker list, and the ONLY one of these three files a browser downloads.
 *
 * It carries no code arrays and no prose — a slug, a label and a lowercase
 * search blob — because the whole reason the client avoids importing the engine
 * is that the engine drags 517 code rows in with it.
 *
 * 🛑 `search` exists because a label-only filter cannot find what buyers type.
 * Takara Tomy spells it Pegasis and Hasbro spells it Pegasus; a Japanese box
 * says ストームペガシス. All of that is in the corpus as aliases, and a select
 * filtering on the display label alone would find none of it.
 */
const optionLabel = (e) => (e.code ? `${e.name} — ${e.code}` : e.name);
const searchBlob = (e) =>
  [e.name, e.code ?? "", ...e.aliases]
    .join(" ")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/\\s+/g, " ")
    .trim();

const modelOptionsBody = entries
  .map(
    (e) =>
      `  { slug: ${JSON.stringify(e.slug)}, label: ${JSON.stringify(optionLabel(e))}, ` +
      `generation: ${JSON.stringify(e.generation)}, categoryId: ${JSON.stringify(e.categoryId)}, ` +
      `recordedCodes: ${codeCountBySlug.get(e.slug) ?? 0}, search: ${JSON.stringify(searchBlob(e))} },`,
  )
  .join("\n");

const modelOptionsOut = `/**
 * GENERATED by scripts/gen-authenticity-index.mjs — do not edit by hand.
 *
 * ${entries.length} canonical beys as picker options, for the model select on
 * /tools/authenticity. Client-safe and deliberately small — no code tables, no
 * prose, no engine import.
 *
 * Re-run after any corpus change: node scripts/gen-authenticity-index.mjs
 */
import type { GenerationId } from "../types";

export interface ModelOption {
  readonly slug: string;
  /** What the user reads: "Lightning L-Drago 100HF — BB-43". */
  readonly label: string;
  readonly generation: GenerationId;
  /** The real category leaf, so a pick can link at the model's own page. */
  readonly categoryId: string;
  /** How many box codes are recorded against it. 0 for most. */
  readonly recordedCodes: number;
  /** Lowercased name + retail code + every alias, for matching what was typed. */
  readonly search: string;
}

export const MODEL_OPTIONS: readonly ModelOption[] = [
${modelOptionsBody}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
fs.writeFileSync(OUT_MODEL_CODES, modelCodesOut, "utf8");
fs.writeFileSync(OUT_MODEL_OPTIONS, modelOptionsOut, "utf8");
console.log(
  `gen-authenticity-index: wrote ${entries.length} beys (${withCode} with codes) -> ${path.relative(ROOT, OUT)}`,
);
console.log(
  `  ${modelCodes.length} models carry a recorded box code -> ${path.relative(ROOT, OUT_MODEL_CODES)}`,
);
console.log(`  ${entries.length} picker options -> ${path.relative(ROOT, OUT_MODEL_OPTIONS)}`);
console.log(`  by generation: ${JSON.stringify(byGeneration)}`);
