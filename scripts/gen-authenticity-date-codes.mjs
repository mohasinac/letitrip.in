#!/usr/bin/env node
/*
 * WHY: The MFB box-code tables are now 495 original codes, 18 midfake codes and
 *      4 codes the sources CONTRADICT EACH OTHER about. Transcribing that by
 *      hand puts a wrong code in front of a buyer about to spend money, and a
 *      single transposed digit is invisible in review. So it is PARSED from the
 *      three archived primary sources.
 *
 * WHAT: Emits two files from `buildDateCodeTables()`:
 *       - src/features/authenticity/data/date-codes.generated.ts   (the tables)
 *       - src/features/authenticity/data/knowledge-sizes.generated.ts (counts)
 *
 *       The PARSE lives in scripts/lib/authenticity-sources.mjs and is shared
 *       with the Firestore seed emitter, so the two deliveries cannot drift
 *       (Root Cause #75).
 *
 * 🛑 The counts live in their OWN tiny module on purpose. The client component
 *    renders "what this tool knows" and needs four integers; importing them from
 *    the engine pulled the engine, the 495-row code table and the 220-row
 *    canonical index into the browser bundle for the sake of those integers.
 *
 * 🛑 Rows are emitted as JSON object literals, one per line. Quoted keys are
 *    valid TypeScript, and it means the parity audit can `JSON.parse` a row
 *    instead of pattern-matching a hand-formatted one — the regex it used
 *    before had to be edited every time a field was added, and an audit that
 *    silently stops matching is worse than no audit (Root Cause #84).
 *
 * Run: node scripts/gen-authenticity-date-codes.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { buildCanonicalIndex, buildDateCodeTables } from "./lib/authenticity-sources.mjs";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "src/features/authenticity/data/date-codes.generated.ts");
const SIZES_OUT = path.join(ROOT, "src/features/authenticity/data/knowledge-sizes.generated.ts");

const { original, midfake, unclear, contested, counts, yearGaps } = buildDateCodeTables();
const canonical = buildCanonicalIndex();

/** One row, one line, parseable by both TypeScript and `JSON.parse`. */
const ser = (g) =>
  `  ${JSON.stringify({
    code: g.code,
    products: g.products,
    regions: g.regions,
    packaging: g.packaging,
    notes: g.notes,
    families: g.families,
    sources: g.sources,
    uncertain: g.uncertain,
    derivedDate: g.derivedDate,
    sourceDateDiffers: g.statedDiffers,
    ...(g.recordedOriginalBy ? { recordedOriginalBy: g.recordedOriginalBy } : {}),
    ...(g.recordedMidfakeBy ? { recordedMidfakeBy: g.recordedMidfakeBy } : {}),
  })},`;

const conflicts = original.filter((g) => g.statedDiffers).map((g) => g.code);
const regions = [...new Set(original.flatMap((g) => g.regions))].sort();

const out = `/**
 * GENERATED by scripts/gen-authenticity-date-codes.mjs — do not edit by hand.
 *
 * Parsed from three archived sources in
 * docs/research/beyblade-authenticity-2026-10/sources/:
 *   reddit-kzyzt1.md                 — the r/Beyblade reference post by
 *                                      u/GodKillgroth (18.01.2021, body edited
 *                                      25.04.2021), year by year.
 *   godkillgroth-model-codes.md      — the same author's later model-by-model,
 *                                      region-by-region compilation.
 *   godkillgroth-midfake-codes.md    — the Sonokong high-quality fakes and the
 *                                      Chinese midfake batch codes.
 *
 * ${original.length} original codes · ${midfake.length} midfake · ${contested.length} CONTESTED · ${unclear.length} unresolved
 * from ${counts.redditRows} + ${counts.modelListRows} + ${counts.midfakeListRows} source rows across ${counts.models} models and ${regions.length} regions
 * (${regions.join(", ")}).
 *
 * 🛑 THE CONTESTED TABLE IS NOT AN EDGE CASE — read it before using either of
 * the other two. ${contested.length} codes are recorded as GENUINE by one source and as a
 * midfake batch by another (${contested.map((c) => c.code).join(", ")}). Resolving that by table
 * precedence would be a coin flip with a person's money on it in both
 * directions: pick midfake and the tool accuses the holder of a genuine box;
 * pick original and it reassures the holder of a fake. They are in neither
 * table, and the engine reports both readings.
 *
 * 🛑 \`sources\` is per row and the three are NOT equally strong. The reddit post
 * has a public permalink, a score and a comment thread; the two later files were
 * received as a file drop with no URL recorded. A row only the drop carries is
 * reported, not verified.
 *
 * \`derivedDate\` is computed FROM THE CODE under the month-day-year reading the
 * post states. \`sourceDateDiffers\` marks the ${conflicts.length} code(s) where the post's own
 * written date disagrees with its own rule${conflicts.length ? ` (${conflicts.join(", ")})` : ""} — surfaced to the user as a
 * source inconsistency, never silently resolved.
 *
 * 🛑 The reddit post's own per-year counts are INFLATED:
${yearGaps.length ? yearGaps.map((g) => ` *   ${g}`).join("\n") : " *   (no gaps)"}
 * Treat "111 codes" from any retelling of that post as wrong.
 *
 * 🛑 The month-day-year reading is DISPUTED. See the research README; the engine
 * shows both readings at runtime. These tables are the sources' data, not a
 * ruling.
 *
 * ${counts.resolvedUnclear} New Boy (Middle East) code(s) the reddit post could only call "seems
 * legit" are now in the ORIGINAL table, because the later model-by-model list
 * records each of them under a real New Boy release. Each carries that history
 * in \`notes\` rather than being quietly upgraded.
 *
 * Re-run: node scripts/gen-authenticity-date-codes.mjs
 */

/** Which archived file a row came from. */
export type AuthenticitySourceId =
  | "reddit-kzyzt1"
  | "godkillgroth-model-codes"
  | "godkillgroth-midfake-codes";

/**
 * Which kind of midfake batch a code belongs to. The two are different claims
 * and must not be collapsed:
 *
 * - \`taiwan-batch\` — the reddit post's original midfake set: Takara-Tomy
 *   blueprints, Taiwanese production, reduced quality.
 * - \`sonokong-highquality\` — Korean boxes that reproduce the importer panel,
 *   both logos and a plausible barcode. Packaging inspection does not settle one.
 * - \`chinese-font\` — 🛑 the CODE is not the discriminator here. The source's own
 *   note on three of these is "the code itself should be authentic however the
 *   font looks like a midfake one". What differs is the printed typeface.
 */
export type MidfakeFamily = "taiwan-batch" | "sonokong-highquality" | "chinese-font";

export interface DateCodeRow {
  readonly code: string;
  /** Products this code has been observed on. */
  readonly products: readonly string[];
  /** Regions of sale: Japan, Taiwan (Funbox Toys), Korea (Sonokong), … */
  readonly regions: readonly string[];
  /** Starter / Booster / Random Booster Vol. N, where a source stated it. */
  readonly packaging: readonly string[];
  /** Per-batch observations: mould variants, importer stickers, launcher colour. */
  readonly notes: readonly string[];
  /** Midfake rows only. */
  readonly families: readonly MidfakeFamily[];
  readonly sources: readonly AuthenticitySourceId[];
  /** The source itself hedged — a blurry photo, or two codes it could not separate. */
  readonly uncertain: boolean;
  /** Derived from the code, month-day-year reading. Null if the letter is outside A–L. */
  readonly derivedDate: string | null;
  /** True where a source's written date contradicts its own stated rule. */
  readonly sourceDateDiffers: boolean;
}

/** A code the sources disagree about, carrying which source is on which side. */
export interface ContestedDateCodeRow extends DateCodeRow {
  readonly recordedOriginalBy: readonly AuthenticitySourceId[];
  readonly recordedMidfakeBy: readonly AuthenticitySourceId[];
}

/** Codes observed on boxes the sources record as genuine. */
export const ORIGINAL_DATE_CODES: readonly DateCodeRow[] = [
${original.map(ser).join("\n")}
];

/**
 * Codes observed on midfake batches — Takara-Tomy-blueprint product of reduced
 * quality. 🛑 NOT counterfeits, and there is no official Takara Tomy statement
 * acknowledging these batches at all.
 */
export const MIDFAKE_DATE_CODES: readonly DateCodeRow[] = [
${midfake.map(ser).join("\n")}
];

/**
 * 🛑 Codes the sources CONTRADICT each other about. Neither reading may be
 * presented as the answer; the engine shows both and asks for a physical check.
 */
export const CONTESTED_DATE_CODES: readonly ContestedDateCodeRow[] = [
${contested.map(ser).join("\n")}
];

/**
 * Regional releases no source could settle. Empty as of the 2026-10-19 merge —
 * every row the reddit post left unresolved was resolved by the later
 * model-by-model list. Kept because the next source drop can reopen one, and an
 * empty table is honest where a deleted one quietly changes what the engine can
 * express.
 */
export const UNCLEAR_DATE_CODES: readonly DateCodeRow[] = [
${unclear.map(ser).join("\n")}
];
`;

const sizes = `/**
 * GENERATED by scripts/gen-authenticity-date-codes.mjs — do not edit by hand.
 *
 * 🛑 Deliberately TINY and dependency-free. The checker's client component
 * renders these four numbers in its "what this tool actually knows" panel;
 * importing them from the engine shipped the engine, the ${original.length}-row code table
 * and the ${canonical.length}-row canonical index to every visitor's browser for four
 * integers. Import this module from client code, never \`../engine\`.
 *
 * Re-run: node scripts/gen-authenticity-date-codes.mjs
 */
export const KNOWLEDGE_BASE_SIZES = {
  canonicalBeys: ${canonical.length},
  originalCodes: ${original.length},
  midfakeCodes: ${midfake.length},
  contestedCodes: ${contested.length},
  unclearCodes: ${unclear.length},
  /** Models the model-by-model source covers, each with per-region batches. */
  modelsWithCodeHistory: ${counts.models},
  regions: ${regions.length},
} as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
fs.writeFileSync(SIZES_OUT, sizes, "utf8");
console.log(
  `gen-authenticity-date-codes: ${original.length} original / ${midfake.length} midfake / ` +
    `${contested.length} contested / ${unclear.length} unclear -> ${path.relative(ROOT, OUT)}`,
);
console.log(`  + knowledge sizes -> ${path.relative(ROOT, SIZES_OUT)}`);
if (conflicts.length) console.log(`  source self-contradictions flagged: ${conflicts.join(", ")}`);
if (contested.length) console.log(`  🛑 contested codes: ${contested.map((c) => c.code).join(", ")}`);
