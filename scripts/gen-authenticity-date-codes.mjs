#!/usr/bin/env node
/*
 * WHY: The MFB box-code table is 98 original entries plus three midfake
 *      families. Transcribing that by hand puts a wrong code in front of a
 *      buyer about to spend money, and a single transposed digit is invisible
 *      in review. So it is PARSED from the archived primary source.
 *
 * WHAT: Emits src/features/authenticity/data/date-codes.generated.ts from
 *       `buildDateCodeTables()`. The PARSE lives in
 *       scripts/lib/authenticity-sources.mjs and is shared with the Firestore
 *       seed emitter, so the two deliveries cannot drift (Root Cause #75).
 *
 * Run: node scripts/gen-authenticity-date-codes.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { buildDateCodeTables } from "./lib/authenticity-sources.mjs";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "src/features/authenticity/data/date-codes.generated.ts");

const { original, midfake, unclear, counts, yearGaps } = buildDateCodeTables();

const ser = (g) =>
  `  { code: ${JSON.stringify(g.code)}, products: ${JSON.stringify(g.products)}, ` +
  `distributors: ${JSON.stringify(g.distributors)}, ` +
  `derivedDate: ${g.derivedDate === null ? "null" : JSON.stringify(g.derivedDate)}, ` +
  `sourceDateDiffers: ${g.statedDiffers} },`;

const conflicts = original.filter((g) => g.statedDiffers).map((g) => g.code);

const out = `/**
 * GENERATED by scripts/gen-authenticity-date-codes.mjs — do not edit by hand.
 *
 * Parsed from docs/research/beyblade-authenticity-2026-10/sources/reddit-kzyzt1.md
 * (archived verbatim body of the r/Beyblade reference post by u/GodKillgroth,
 * 18.01.2021, body edited 25.04.2021).
 *
 * ${original.length} distinct original codes (${counts.originalRows} product rows)
 * ${midfake.length} distinct midfake codes (${counts.midfakeRows} product rows)
 * ${unclear.length} distinct unclear codes (${counts.unclearRows} product rows)
 *
 * \`derivedDate\` is computed FROM THE CODE under the month-day-year reading the
 * post states. \`sourceDateDiffers\` marks the ${conflicts.length} code(s) where
 * the post's own written date disagrees with its own rule${conflicts.length ? ` (${conflicts.join(", ")})` : ""} —
 * surfaced to the user as a source inconsistency, never silently resolved.
 *
 * 🛑 The source's own per-year counts are INFLATED. It claims 111 original
 * entries and lists ${counts.originalRows}:
${yearGaps.length ? yearGaps.map((g) => ` *   ${g}`).join("\n") : " *   (no gaps)"}
 * Treat "111 codes" from any retelling of this post as wrong.
 *
 * 🛑 The month-day-year reading is DISPUTED. See the research README; the engine
 * shows both readings at runtime. This table is the post's data, not a ruling.
 *
 * Re-run: node scripts/gen-authenticity-date-codes.mjs
 */

export interface DateCodeRow {
  readonly code: string;
  /** Products this code has been observed on. */
  readonly products: readonly string[];
  /** \`Takara Tomy\` / \`Sonokong\` / \`Random Booster TT\` where the post recorded one. */
  readonly distributors: readonly string[];
  /** Derived from the code, month-day-year reading. Null if the letter is outside A–L. */
  readonly derivedDate: string | null;
  /** True where the source's written date contradicts its own stated rule. */
  readonly sourceDateDiffers: boolean;
}

/** Codes observed on confirmed-genuine Takara Tomy / Sonokong boxes. */
export const ORIGINAL_DATE_CODES: readonly DateCodeRow[] = [
${original.map(ser).join("\n")}
];

/**
 * Codes observed on midfake batches — Takara-Tomy-blueprint product of reduced
 * quality, produced in Taiwan. 🛑 NOT counterfeits, and there is no official
 * Takara Tomy statement acknowledging these batches at all.
 */
export const MIDFAKE_DATE_CODES: readonly DateCodeRow[] = [
${midfake.map(ser).join("\n")}
];

/**
 * New Boy (Middle East) regional releases the source itself could not settle,
 * annotated there as "code seems legit". Carried with the hedge intact.
 */
export const UNCLEAR_DATE_CODES: readonly DateCodeRow[] = [
${unclear.map(ser).join("\n")}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
console.log(
  `gen-authenticity-date-codes: ${original.length} original / ${midfake.length} midfake / ${unclear.length} unclear codes -> ${path.relative(ROOT, OUT)}`,
);
if (conflicts.length) console.log(`  source self-contradictions flagged: ${conflicts.join(", ")}`);
