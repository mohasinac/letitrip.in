#!/usr/bin/env node
/*
 * The master traceability ledger: every case × every run.
 *
 *   node scripts/tester-traceability.mjs --runs run-a,run-b,... --labels "Run 1,Run 2"
 *   node scripts/tester-traceability.mjs --auto        # every run on disk, oldest first
 *
 * Writes:
 *   test-traceability.md                  the spec's matrix
 *   tester/.tester-runs/_failures.json    { id, label, runs[], ev } per open failure
 *
 * 🛑 WHY THIS DID NOT EXIST
 *
 * The pieces were all here and never joined. `build-testing-status.mjs` already
 * walks every run directory but only aggregates PER RUN (pass/fail/blocked
 * counts). `_failures.json` already has the right per-case shape and is already
 * CONSUMED by that script — but nothing in the repo WRITES it, so it sat
 * hand-maintained, 39 entries, with run names (`all1`, `v2`) predating the
 * current `run-<ts>` scheme. This script is the missing join.
 *
 * 🛑 A CASE ABSENT FROM A RUN IS NOT A PASS
 *
 * Every run after the baseline is scoped to a subset, so most cases have no
 * verdict in most runs. Those cells render `-`, never PASS. Treating "not
 * re-tested" as "still passing" is precisely the false-green this whole ledger
 * exists to prevent: the Final column is derived from the LAST RUN THAT
 * ACTUALLY TESTED the case, and says so.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { readRun, listRuns, indexById, esc, PASS, FAIL, BLOCKED } from "./lib/tester-runs.mjs";

function flag(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) return fallback;
  const next = process.argv[i + 1];
  return next && !next.startsWith("--") ? next : true;
}

const auto = flag("auto") === true;
const runsArg = flag("runs");
const labelsArg = flag("labels");

let runIds;
if (auto || !runsArg || runsArg === true) {
  runIds = listRuns();
} else {
  runIds = String(runsArg).split(",").map((s) => s.trim()).filter(Boolean);
}
if (runIds.length === 0) {
  console.error("✗ no runs found. Use --runs a,b or --auto.");
  process.exit(2);
}

const labels =
  labelsArg && labelsArg !== true
    ? String(labelsArg).split(",").map((s) => s.trim())
    : runIds.map((_, i) => `Run ${i + 1}`);

const runs = runIds.map((id, i) => {
  const data = readRun(id);
  return { id, label: labels[i] ?? id, index: indexById(data.records), records: data.records };
});

// Union of every case id ever seen, plus the richest label we have for it.
const allIds = new Map();
for (const r of runs) {
  for (const rec of r.records) {
    const prev = allIds.get(rec.id);
    if (!prev || (!prev.label && rec.label)) {
      allIds.set(rec.id, { label: rec.label, href: rec.href, humanChannel: rec.requiresHumanChannel });
    }
  }
}

const SHORT = { [PASS]: "PASS", [FAIL]: "FAIL", [BLOCKED]: "BLOCKED" };

/**
 * The Final column.
 *
 * Walks runs newest-first and returns the first real verdict. A case last
 * tested in Run 1 and never re-tested reports Run 1's answer, tagged with
 * where it came from — not an optimistic carry-forward.
 */
function finalFor(id) {
  for (let i = runs.length - 1; i >= 0; i--) {
    const rec = runs[i].index.get(id);
    if (rec) return { status: rec.status, from: runs[i].label, rec };
  }
  return null;
}

const rows = [];
for (const [id, meta] of allIds) {
  const cells = runs.map((r) => {
    const rec = r.index.get(id);
    return rec ? SHORT[rec.status] : "-";
  });
  const fin = finalFor(id);
  rows.push({ id, meta, cells, final: fin });
}

// Most interesting first: anything not currently passing, then by id.
const rank = (r) => (r.final?.status === PASS ? 2 : r.final?.status === FAIL ? 0 : 1);
rows.sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id));

/*
 * 🛑 ACCEPTED EXCEPTION = human channel AND BLOCKED. The flag alone is not
 * enough, and getting this wrong loses a real defect.
 *
 * `requiresHumanChannel` means "cannot be FULLY automated", not "ignore its
 * result". A tester can get well into such a case and observe a genuine failure
 * before running out of channel — in run-1789432098900 exactly one did
 * (…forgot-reset-password-pages, which found the same defect on a second form).
 * Classifying it by the flag counted it as permanently-manual and dropped it
 * from the open list, silently.
 *
 * Same rule in tester-carry-forward.mjs; the two must agree or the ledger and
 * the retest scope disagree about what is outstanding.
 */
const isAccepted = (r) => r.meta.humanChannel && r.final?.status === BLOCKED;
const open = rows.filter((r) => r.final && r.final.status !== PASS && !isAccepted(r));
const acceptedRows = rows.filter(isAccepted);
const passing = rows.filter((r) => r.final?.status === PASS);

const L = [];
const w = (s = "") => L.push(s);

w(`# Test Traceability`);
w();
w(`Every checklist case against every tester run, oldest run first. Generated by`);
w(`\`scripts/tester-traceability.mjs\`; regenerate after every Test Run and every`);
w(`Fix Run.`);
w();
w(`- \`-\` means the case was **not in that run's scope**, not that it passed.`);
w(`- **Final** is the verdict from the most recent run that actually tested the`);
w(`  case, and names which run that was.`);
w(`- Accepted exceptions (need a channel no automation can supply) are listed`);
w(`  separately and excluded from the open-issue count.`);
w();

w(`## Runs`);
w();
w(`| Label | Run ID | Cases with a verdict |`);
w(`|---|---|---|`);
for (const r of runs) w(`| ${r.label} | \`${r.id}\` | ${r.records.length} |`);
w();

w(`## Summary`);
w();
w(`| | Count |`);
w(`|---|---|`);
w(`| Cases tracked | ${rows.length} |`);
w(`| Currently passing | ${passing.length} |`);
w(`| Open (FAIL or BLOCKED) | ${open.length} |`);
w(`| Accepted exceptions | ${acceptedRows.length} |`);
w();

const header = `| Test Case | ${runs.map((r) => r.label).join(" | ")} | Final | Final from |`;
const sep = `|---|${runs.map(() => "---").join("|")}|---|---|`;

w(`## Open cases`);
w();
w(`Not passing as of their most recent test. These are what the next Fix Run and`);
w(`Test Run exist to close.`);
w();
if (open.length) {
  w(header); w(sep);
  for (const r of open) {
    w(`| \`${r.id}\` | ${r.cells.join(" | ")} | ${r.final.status} | ${r.final.from} |`);
  }
} else {
  w(`_None._`);
}
w();

w(`## Accepted exceptions`);
w();
if (acceptedRows.length) {
  w(header); w(sep);
  for (const r of acceptedRows) {
    w(`| \`${r.id}\` | ${r.cells.join(" | ")} | ${r.final?.status ?? "-"} | ${r.final?.from ?? "-"} |`);
  }
} else {
  w(`_None._`);
}
w();

w(`## Passing cases`);
w();
if (passing.length) {
  w(header); w(sep);
  for (const r of passing) {
    w(`| \`${r.id}\` | ${r.cells.join(" | ")} | ${r.final.status} | ${r.final.from} |`);
  }
} else {
  w(`_None._`);
}
w();

mkdirSync("tester/.tester-runs", { recursive: true });
writeFileSync("test-traceability.md", L.join("\n"));

/*
 * _failures.json — the shape build-testing-status.mjs already expects:
 * { id, label, runs: [<run labels where it was not passing>], ev }
 */
const failures = open.map((r) => ({
  id: r.id,
  label: r.meta.label || "",
  runs: runs.filter((run) => {
    const rec = run.index.get(r.id);
    return rec && rec.status !== PASS;
  }).map((run) => run.label),
  ev: esc(r.final.rec.comment ?? "").slice(0, 300),
}));
writeFileSync("tester/.tester-runs/_failures.json", JSON.stringify(failures, null, 2) + "\n");

console.log(`✓ test-traceability.md`);
console.log(`  ${rows.length} cases across ${runs.length} run(s)`);
console.log(`  passing ${passing.length} · open ${open.length} · accepted ${acceptedRows.length}`);
console.log(`✓ tester/.tester-runs/_failures.json (${failures.length} open)`);
