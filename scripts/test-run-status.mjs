#!/usr/bin/env node
/*
 * G2 — every number is computed from disk, never typed.
 *
 * 🛑 THE FAILURE THIS PREVENTS. In an earlier run a hand-kept tally reported 17
 * failures where the verdict files held 15. The prose had been counting
 * calibration controls, and nothing could catch it, because the only other copy
 * of the number WAS the prose. A count that lives in two places has already
 * drifted — it just has not been noticed yet.
 *
 * So this rewrites the counter block of docs/TEST-RUN-3.md in place, from
 * tally(). The Stop hook calls it on every fire. I never type a count into the
 * document; if a number looks wrong the fix belongs in lib/test-run.mjs.
 *
 * It rewrites ONLY between the COUNTER markers — and then spawns
 * `test-run-table.mjs`, which rewrites the row table between its OWN markers.
 * Both halves come from the same verdict files, so both are refreshed by this
 * one command. They used to have two cadences (this one on every Stop-hook
 * fire, the table whenever somebody remembered) and the rows silently lagged
 * the counter by up to a cycle.
 *
 * Usage:
 *   node scripts/test-run-status.mjs            # rewrite the block, print a summary
 *   node scripts/test-run-status.mjs --json     # machine-readable, writes nothing
 *   node scripts/test-run-status.mjs --quiet    # rewrite silently (the hook uses this)
 *
 * Exit: 0 always unless the document is missing its markers (2) — a reporting
 * aid that can fail the run would be worse than no reporting aid.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
import { CHECKLIST_DOC, REPO, flag, tally } from "./lib/test-run.mjs";

const BEGIN = "<!-- COUNTER:BEGIN — generated by scripts/test-run-status.mjs, do not edit by hand -->";
const END = "<!-- COUNTER:END -->";

const t = tally();

if (flag("json") === true) {
  const { failedCases, fixes, ...rest } = t;
  console.log(JSON.stringify({ ...rest, failedCount: failedCases.length, fixCount: fixes.length }));
  process.exit(0);
}

const pct = t.casesTotal ? Math.round((t.casesDone / t.casesTotal) * 100) : 0;
const verified = t.fail === 0 ? "—" : `${t.fixed}/${t.fail}`;

const block = [
  BEGIN,
  "",
  "| | |",
  "|---|---|",
  `| Run id | \`${t.runId}\` |`,
  `| Batches | **${t.batchesDone} / ${t.batchesTotal || "?"}** |`,
  `| Cases | **${t.casesDone} / ${t.casesTotal || "?"}** (${pct}%) |`,
  `| Cycle | ${t.cycle} of ${t.totalCycles} |`,
  `| Next deploy | batch ${t.nextDeploy} |`,
  `| Last updated | ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC |`,
  "",
  `\`\`\``,
  `pass ${t.pass} · fail ${t.fail} · null ${t.abstain}`,
  `fixed ${verified}`
    + (t.deferred ? ` · deferred ${t.deferred}` : "")
    + ` · open ${t.open} · needs-human ${t.manual}`,
  `\`\`\``,
  "",
  t.open > 0
    ? `> ▸ **${t.open} failure(s) not yet fixed.** Fixes land in one phase at the
> next 25-batch milestone, with the deploy that makes them re-drivable — not mid-batch.`
    : "> No open defects.",
  "",
  END,
].join("\n");

if (!existsSync(CHECKLIST_DOC)) {
  console.error(`✗ ${CHECKLIST_DOC} does not exist — create it before running status.`);
  process.exit(2);
}

const doc = readFileSync(CHECKLIST_DOC, "utf8");
const i = doc.indexOf(BEGIN);
const j = doc.indexOf(END);
if (i === -1 || j === -1 || j < i) {
  console.error(`✗ ${CHECKLIST_DOC} is missing its COUNTER:BEGIN/END markers.`);
  console.error("  The block is rewritten in place; without the markers this would have to");
  console.error("  rewrite the whole file, and the case table below is hand-written.");
  process.exit(2);
}

const next = doc.slice(0, i) + block + doc.slice(j + END.length);
if (next !== doc) writeFileSync(CHECKLIST_DOC, next, "utf8");

/*
 * 🛑 Regenerate the ROW TABLE too, in the same command.
 *
 * Both halves of that document are generated from the same verdict files, but
 * only this one was wired to anything that runs by itself: the Stop hook calls
 * `test-run-status.mjs` every turn, while `test-run-table.mjs` was a separate
 * step somebody had to remember. So the counter block tracked reality and the
 * rows beneath it lagged by up to a whole cycle — caught by the user reading
 * the file and asking why it still said 21 batches when 22 were recorded.
 *
 * One document cannot have two refresh cadences. A reader has no way to tell
 * which half is stale, and the stale half looks exactly like a run that stopped.
 *
 * Spawned rather than imported because the table script is a top-level program
 * (it reads argv, writes the file, prints a summary) and importing it for its
 * side effects would make the order of two module-scope writes to one file
 * load-order-dependent. `stdio: "ignore"` keeps this script's own output the
 * single summary it has always been; a non-zero exit is surfaced rather than
 * swallowed, because a table that failed to write is the thing being fixed.
 */
const table = spawnSync(process.execPath, [resolve(REPO, "scripts/test-run-table.mjs")], {
  cwd: REPO,
  stdio: "ignore",
});
if (table.status !== 0) {
  console.error(
    `✗ scripts/test-run-table.mjs exited ${table.status} — the counter above is current but the ROW TABLE is not.`,
  );
  process.exitCode = 1;
}

if (flag("quiet") !== true) {
  console.log(`${t.runId}: ${t.batchesDone}/${t.batchesTotal || "?"} batches · ${t.casesDone}/${t.casesTotal || "?"} cases`);
  console.log(
    `  pass ${t.pass} · fail ${t.fail} · null ${t.abstain} · fixed ${verified}`
      + (t.deferred ? ` · deferred ${t.deferred}` : "")
      + ` · open ${t.open}`,
  );
  if (t.open > 0) {
    console.log("");
    console.log("  OPEN (queued for the next 25-batch fix phase, not blocking):");
    const fixedIds = new Set(t.fixes.map((f) => f.caseId));
    for (const f of t.failedCases.filter((c) => !fixedIds.has(c.id)).slice(0, 15)) {
      console.log(`    ${f.key}  ${f.id}`);
    }
  }
}
