#!/usr/bin/env node
/**
 * D2 Fix 3 — generate the part code ⇄ name bridge into appkit source.
 *
 * 🛑 GENERATED INTO SOURCE, not read from Firestore, because
 * `buildProductSearchTxt` is SYNCHRONOUS and runs on every product write. A
 * Firestore read there would make the hottest write path in the catalogue
 * depend on a second collection, and `searchTxt` must be deterministic for the
 * same input or the backfill and the app disagree (audit-search-parity).
 *
 * Only rows with BOTH a code and a distinct name can bridge — measured: **23**
 * of 759. The rest are name-only and already searchable by name, so they need
 * no alias. That is the honest scope rather than a claim of 759.
 *
 * Run after `extract-part-glossary.mjs`:
 *   node scripts/generate-part-alias-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const GLOSSARY = resolve(process.cwd(), "docs/research/part-composition-2026-10/part-glossary.json");
const OUT = resolve(process.cwd(), "appkit/src/_internal/shared/search/part-aliases.ts");

const rows = JSON.parse(readFileSync(GLOSSARY, "utf8"))
  .filter((r) => r.code && r.name && r.name.toUpperCase() !== r.code.toUpperCase())
  // `Bottom: Rubber Flat` → the searchable part is "rubber flat", not the prefix.
  .map((r) => ({
    code: String(r.code),
    name: String(r.name).replace(/^(?:4D\s+)?(?:Bottom|Track|Disc|Layer|Blade|Ratchet|Bit)\s*:\s*/i, "").trim(),
    classification: r.classification,
  }))
  .filter((r) => r.name.length >= 3)
  .sort((a, b) => a.code.localeCompare(b.code));

/*
 * 🛑 Emit the classifications as NAMED CONSTANTS, not repeated literals.
 *
 * `audit-code-quality`'s REPEATED_STRING rule fired on the first generated
 * output — "Performance Tip" appeared 5 times — and it was right to. The rule
 * exists for hand-written code, but a generator that emits a violation is a
 * generator whose output nobody can commit, so the fix belongs HERE rather
 * than in a suppression marker (Root Cause #22: a marker is the violation
 * hidden from the counter, not removed).
 */
const NL = String.fromCharCode(10);
const classifications = [...new Set(rows.map((r) => r.classification))].sort();
const constName = (c) => "CLS_" + c.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
const clsBlock = classifications
  .map((c) => "const " + constName(c) + " = " + JSON.stringify(c) + ";")
  .join(NL);
const body = rows.map((r) =>
  "  { code: " + JSON.stringify(r.code) + ", name: " + JSON.stringify(r.name)
    + ", classification: " + constName(r.classification) + " },"
).join(NL);

writeFileSync(OUT, `/**
 * GENERATED by \`scripts/generate-part-alias-map.mjs\` — do not hand-edit.
 * Source: \`docs/research/part-composition-2026-10/part-glossary.json\` (E4b).
 *
 * D2 Fix 3 — the part code ⇄ name bridge, so "rubber flat" finds \`RF\` listings
 * and \`RF\` finds them too. Firestore cannot fuzzy-match, but nothing stops us
 * indexing MORE tokens per document, which is what this is for.
 *
 * 🛑 Only rows carrying BOTH a code and a distinct name can bridge: **${rows.length}**
 * of 759 glossary entries. The remaining 736 are name-only and already
 * searchable by name, so they need no alias — that is the measured scope, not
 * a shortfall.
 *
 * 🛑 In SOURCE rather than read from Firestore because \`buildProductSearchTxt\`
 * is synchronous and runs on every product write; and \`searchTxt\` must be
 * deterministic for the same input, or the app and
 * \`backfill-search-txt.mjs\` emit different tokens for one product
 * (audit-search-parity's own stated failure mode).
 *
 * 🛑 It shares the 600-token cap with D0's generated misspelling variants, and
 * that cap TRUNCATES SILENTLY. Measured headroom at generation time: the worst
 * live product carried 199 tokens, so 401 spare. Re-measure before adding a
 * third token source.
 */

export interface PartAlias {
  /** The short code as printed on the part and in listing titles. */
  code: string;
  /** The spoken name — what a buyer types. */
  name: string;
  classification: string;
}

${clsBlock}

export const PART_ALIASES: readonly PartAlias[] = [
${body}
] as const;

/**
 * Tokens to add for one piece of text — the COUNTERPART of anything matched.
 *
 * A listing titled "Storm Pegasus 105RF" gets "rubber flat"; one titled
 * "… Rubber Flat" gets "rf". Nothing is added when neither appears, so an
 * unrelated product pays no tokens at all.
 *
 * 🛑 Word-boundary matched on the CODE. A bare \`substring\` test puts "quake"
 * on every product containing a letter Q — codes here are 1–5 characters, so
 * an unanchored match is worse than no match.
 */
export function partAliasTokens(text: string): string[] {
  if (!text) return [];
  const words = text.toLowerCase().replace(/[^a-z0-9]+/g, " ").split(" ").filter(Boolean);
  const hay = \` \${words.join(" ")} \`;
  const out: string[] = [];

  for (const { code, name } of PART_ALIASES) {
    const c = code.toLowerCase().replace(/[^a-z0-9]+/g, "");
    const n = name.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
    if (!c || !n) continue;

    /*
     * 🛑 A CODE IS WRITTEN SUFFIXED TO ITS HEIGHT, which a word-boundary match
     * misses entirely: real titles say "Storm Pegasus 105RF" and "Dran Sword
     * 3-60F", never " RF ". So a digit-prefixed suffix counts as a match.
     */
    const suffixed = words.some((w) => {
      /*
       * 🛑 The code must be the WHOLE alphabetic suffix, not any suffix.
       * "105rf".endsWith("f") is true, so a plain endsWith aliased every
       * Rubber Flat listing to "flat" as well — a wrong second tip on a
       * correct match, which is the kind of noise that makes a search feature
       * read as broken rather than absent.
       */
      const m = /^([0-9][0-9-]*)([a-z]+)$/.exec(w);
      return !!m && m[2] === c;
    });

    /*
     * 🛑 A BARE code only counts at 2+ characters. "Dranzer F" is a MODEL
     * name — F there is not the Flat tip — and single letters are common in
     * model names, so a 1-character bare match would alias a large part of the
     * catalogue to a tip it does not have. The digit-prefixed form above still
     * catches "105F", which is where a 1-character code actually appears.
     */
    const bare = c.length >= 2 && hay.includes(\` \${c} \`);

    if (suffixed || bare) out.push(n);
    if (hay.includes(\` \${n} \`)) out.push(c);
  }
  return [...new Set(out)];
}
`);

console.log(`wrote ${rows.length} aliases to ${OUT.replace(process.cwd(), ".")}`);
for (const r of rows.slice(0, 8)) console.log(`  ${r.code.padEnd(6)} <-> ${r.name}`);
