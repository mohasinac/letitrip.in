/**
 * POST /api/orders/[id]/refund
 *
 * Issue a full or partial refund on an order. Only admin or the owning store's
 * seller may call this endpoint. Buyers submit a refund *request* via the UI —
 * refunds are always issued by staff/seller after review.
 *
 * Body: ProcessRefundInput (minus orderId, refundedBy — those are injected here).
 * Returns: { refundId }
 */

import { withProviders } from "@/providers.config";
import { z } from "zod";
import { isAdminUser } from "@mohasinac/appkit/features/auth/role-predicates";
import { storeRepository } from "@mohasinac/appkit/features/stores/repository/store.repository";
import { successResponse, errorResponse } from "@mohasinac/appkit/next/api/api-response";
import { createRouteHandler } from "@mohasinac/appkit/next/api/routeHandler";
import { orderRepository } from "@mohasinac/appkit";
import { processRefundAction, RETURN_REASON } from "@mohasinac/appkit/server";
import { ROLES_STORE_WRITE } from "@/constants";

const bodySchema = z.object({
  type: z.enum(["full", "partial"]),
  amount: z.number().positive(),
  reasonCode: z.enum(RETURN_REASON),
  reasonNote: z.string().max(500).optional(),
  itemIds: z.array(z.string()).optional(),
  confirmIrrevocable: z.literal(true),
  /*
   * 🛑 REQUIRED (D2). One key per form OPEN, generated by the client.
   *
   * The refund entry id is `sha256(idempotencyKey)` and a claim document is
   * created on it BEFORE the gateway is called, so a retry of the same logical
   * request is a no-op. It used to be a server-side `randomUUID()` per call,
   * which cannot be idempotent by construction: a double-clicked button
   * produced two ids and two real gateway refunds.
   */
  idempotencyKey: z.string().min(8).max(200),
  method: z.enum(["phonepe", "manual"]),
  phonepeOrderId: z.string().optional(),
  manualTransactionId: z.string().optional(),
  proofDocumentUrl: z.string().optional(),
  proofDocumentMimeType: z.string().optional(),
});

export const POST = withProviders(
  createRouteHandler<(typeof bodySchema)["_output"]>({
    auth: true,
    roles: [...ROLES_STORE_WRITE],
    schema: bodySchema,
    handler: async ({ user, body, params }) => {
      const id = (params as { id: string }).id;
      const order = await orderRepository.findById(id);
      if (!order) return errorResponse("Order not found", 404);

      if (!isAdminUser(user)) {
        const store = await storeRepository.findByOwnerId(user!.uid);
        if (!store || order.storeId !== store.id)
          return errorResponse("Order not found", 404);
      }

      const b = body!;
      // Type-safe union narrowing for the discriminated union in processRefundAction.
      const refundInput =
        b.method === "phonepe"
          ? {
              orderId: id,
              type: b.type,
              amount: b.amount,
              reasonCode: b.reasonCode,
              ...(b.reasonNote ? { reasonNote: b.reasonNote } : {}),
              ...(b.itemIds ? { itemIds: b.itemIds } : {}),
              confirmIrrevocable: true as const,
              idempotencyKey: b.idempotencyKey,
              refundedBy: user!.uid,
              method: "phonepe" as const,
              phonepeOrderId: b.phonepeOrderId ?? order.paymentId ?? "",
            }
          : {
              orderId: id,
              type: b.type,
              amount: b.amount,
              reasonCode: b.reasonCode,
              ...(b.reasonNote ? { reasonNote: b.reasonNote } : {}),
              ...(b.itemIds ? { itemIds: b.itemIds } : {}),
              confirmIrrevocable: true as const,
              idempotencyKey: b.idempotencyKey,
              refundedBy: user!.uid,
              method: "manual" as const,
              ...(b.manualTransactionId ? { manualTransactionId: b.manualTransactionId } : {}),
              ...(b.proofDocumentUrl ? { proofDocumentUrl: b.proofDocumentUrl } : {}),
              ...(b.proofDocumentMimeType ? { proofDocumentMimeType: b.proofDocumentMimeType } : {}),
            };

      const result = await processRefundAction(refundInput);
      return successResponse(result, "Refund processed");
    },
  }),
);