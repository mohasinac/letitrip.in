import { withProviders } from "@/providers.config";
import { z } from "zod";
import { successResponse, errorResponse } from "@mohasinac/appkit/next/api/api-response";
import { createRouteHandler } from "@mohasinac/appkit/next/api/routeHandler";
import { orderRepository } from "@mohasinac/appkit";
import { processRefundAction } from "@mohasinac/appkit/server";
import { ROLES_ADMIN_MOD } from "@/constants";
import { RETURN_REASON, wouldBeFullRefund } from "@mohasinac/appkit/server";

const refundSchema = z.object({
  amount: z.number().min(1),
  /**
   * Coded, not free text. An admin issuing a refund is recording WHY against
   * the same closed enum the buyer picks from, so the two are comparable and
   * the final-sale gate can reason about it.
   */
  reasonCode: z.enum(RETURN_REASON),
  reasonNote: z.string().max(500).optional(),
  /*
   * 🛑 REQUIRED (D2). One key per form OPEN, generated by the client — so a
   * double-click reuses it and a genuine second refund gets a new one.
   *
   * `processRefundAction` derives the refund entry id from
   * `sha256(idempotencyKey)` and claims a document on it BEFORE calling the
   * gateway. Previously the id was a server-side `randomUUID()` per call,
   * which can never be idempotent: two clicks meant two real gateway refunds.
   *
   * Required rather than optional with a fallback — an optional key would be
   * omitted by exactly the callers that need it most.
   */
  idempotencyKey: z.string().min(8).max(200),
});

export const POST = withProviders(
  createRouteHandler<(typeof refundSchema)["_output"]>({
    auth: true,
    roles: [...ROLES_ADMIN_MOD],
    schema: refundSchema,
    handler: async ({ body, params, user }) => {
      const id = (params as { id: string }).id;
      const order = await orderRepository.findById(id);
      if (!order) return errorResponse("Order not found", 404);

      /*
       * 🛑 A SECOND COPY of the D3 defect lived here: `body.amount >=
       * order.totalPrice`. Unreachable once the non-refundable platform fee is
       * withheld — the largest possible refund is strictly LESS than
       * `totalPrice` — so this always computed `partial`, and it also ignored
       * every prior partial refund.
       *
       * It only ever fed `type: "full" | "partial"`, a LABEL on the entry;
       * `processRefundAction` decides the real `isFull` (which flips the order
       * to `refunded`) via `wouldBeFullRefund` against the refundable base. So
       * the consequence here was a mislabelled row rather than a stuck order —
       * but two tests for one question is how they drift, and this one was
       * already wrong.
       */
      const isFull = wouldBeFullRefund(order, body!.amount);
      const usesPhonePe = order.paymentMethod !== "cod" && !!order.paymentId;

      const result = await processRefundAction(
        usesPhonePe
          ? {
              orderId: id,
              type: isFull ? "full" : "partial",
              amount: body!.amount,
              reasonCode: body!.reasonCode,
              ...(body!.reasonNote ? { reasonNote: body!.reasonNote } : {}),
              refundedBy: user!.uid,
              confirmIrrevocable: true,
              idempotencyKey: body!.idempotencyKey,
              method: "phonepe",
              phonepeOrderId: order.paymentId!,
            }
          : {
              orderId: id,
              type: isFull ? "full" : "partial",
              amount: body!.amount,
              reasonCode: body!.reasonCode,
              ...(body!.reasonNote ? { reasonNote: body!.reasonNote } : {}),
              refundedBy: user!.uid,
              confirmIrrevocable: true,
              idempotencyKey: body!.idempotencyKey,
              method: "manual",
            },
      );

      if (!result.ok) return errorResponse(result.error ?? "Refund failed", 400);
      return successResponse({ id, ...body }, "Order refunded");
    },
  }),
);
